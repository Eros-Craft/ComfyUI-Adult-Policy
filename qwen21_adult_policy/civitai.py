import os
import re
import urllib.request

CIVITAI_DIR = "Qwen/Civitai"
REFUSED_FLAGS = ("poi", "minor", "sfwOnly")     # a real person, a minor, or not for NSFW use


# Civitai files Qwen Image 2.1 under TWO base models (measured 2026-09-24): "Qwen 2.1", and "Qwen 2" for uploads
# made in the days before that tag existed. A "Qwen 2" version counts as 2.1 only when it was published on or after
# the model's release and its own name says 2.1; everything else under "Qwen 2" is the older Qwen-Image 2.0.
QWEN21_BASE = "Qwen 2.1"
QWEN2_BASE = "Qwen 2"
QWEN21_RELEASED = "2026-09-20"
QWEN21_NAME = re.compile(r"2\.1|q21|qw21|qwen21|qwen-21|qwen_21", re.I)


def is_qwen21_upload(version):
    """True when a "Qwen 2"-tagged version is really a Qwen Image 2.1 resource."""
    when = str(version.get("publishedAt") or version.get("createdAt") or "")[:10]
    if not when or when < QWEN21_RELEASED:
        return False
    names = [version.get("name"), (version.get("model") or {}).get("name")]
    names += [f.get("name") for f in (version.get("files") or [])]
    return any(QWEN21_NAME.search(str(n or "")) for n in names)


CIVITAI_HOSTS = ("civitai.com", "civitai.red")


def civitai_safe_url(url, hosts=CIVITAI_HOSTS):
    """Return `url` if it is safe to request, else raise. The Bearer token depends on this.

    A prefix test is NOT a host check: `https://civitai.` is a prefix of `https://civitai.evil.com`,
    and `https://civitai.com@evil.com` has hostname `evil.com`. Either one would have sent the
    user's Civitai token to a stranger, so the hostname is parsed and compared exactly.

    `hosts=None` is for the signed storage URL a download redirects to: its hostname belongs to a
    CDN and cannot be enumerated, so the rules there are https, no userinfo, and a public address:
    which is what stops `file://`, `http://localhost/...` and a redirect aimed at the pod's own
    network.
    """
    import ipaddress
    import socket
    from urllib.parse import urlparse

    u = urlparse(url)
    if u.scheme != "https":
        raise ValueError(f"refusing a non-https URL: {u.scheme or url!r}")
    if u.username or u.password:
        raise ValueError("refusing a URL carrying credentials")
    host = (u.hostname or "").lower()
    if not host:
        raise ValueError(f"refusing a URL with no host: {url!r}")
    if hosts is not None:
        if host not in hosts:
            raise ValueError(f"refusing an unexpected host: {host}")
        return url
    try:
        infos = socket.getaddrinfo(host, 443, proto=socket.IPPROTO_TCP)
    except OSError as e:
        raise ValueError(f"cannot resolve {host}: {e}")
    for info in infos:
        ip = ipaddress.ip_address(info[4][0])
        if (ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved
                or ip.is_multicast or ip.is_unspecified):
            raise ValueError(f"refusing {host}: it resolves to the non-public address {ip}")
    return url


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    """Never follow a redirect on its own: `_fetch_validated` checks every hop first."""

    def redirect_request(self, *a, **k):
        return None


# MEASURED on a live machine, 2026-09-19: civitai.red answers HTTP 403 to urllib's default
# User-Agent ("Python-urllib/3.14") and HTTP 200 to anything else, for the identical URL, with the
# identical Bearer token, from the identical host. Every other explanation looked right and was
# wrong: the token WAS present in the server's environment, the machine COULD reach civitai.red,
# and curl returned 200 for the picker's exact query and every variant of it. Only replaying the
# request the server actually makes, with the same User-Agent, reproduced it.
#
# So the ➕ picker opened, reached its own server-side route, asked Civitai and showed
# "HTTPError: HTTP Error 403: Forbidden" with the package's honest guess that the region was the
# cause. The region was not the cause. A User-Agent was.
#
# It identifies the client honestly and is not a secret, so unlike the Bearer it is safe on every
# hop and is re-applied after a redirect.
FETCH_USER_AGENT = "Mozilla/5.0 (compatible; ComfyUI-Qwen21-AdultPolicy)"


def _fetch_validated(url, *, hosts, redirect_hosts="same", headers=None, timeout=30, max_hops=5, opener=None):
    """Open `url` and follow redirects BY HAND, validating every hop with `civitai_safe_url`.

    `urlopen` follows a 3xx on its own, and V2.3.0 validated only the first URL of the download:
    a signed storage URL that answered with a redirect of its own, to 169.254.169.254, to
    localhost or into the pod's network, would have been fetched with the pod's own reach (the
    SSRF the 2026-09-11 review found). So the opener refuses redirects; the first URL is held to
    `hosts` (the allowlist, or None for the public-address rules); every later hop is held to
    `redirect_hosts` (the same list by default; None for a download, because a storage CDN's
    hostname cannot be listed) and carries NO headers, so a Bearer given for the first hop never
    reaches a host the list did not name. The chain is capped at `max_hops`; a 3xx without a
    Location, or any other HTTP error, is raised as it is.

    Returns the open response for the final 2xx; use it as a context manager.
    """
    import urllib.error
    import urllib.parse
    import urllib.request
    if redirect_hosts == "same":
        redirect_hosts = hosts
    opener = opener or urllib.request.build_opener(_NoRedirect)
    hop = civitai_safe_url(url, hosts=hosts)
    hdrs = dict(headers or {})
    hdrs.setdefault("User-Agent", FETCH_USER_AGENT)
    for _ in range(max_hops + 1):
        try:
            return opener.open(urllib.request.Request(hop, headers=hdrs), timeout=timeout)
        except urllib.error.HTTPError as e:
            location = e.headers.get("Location") if e.headers is not None else None
            try:
                e.close()        # nobody reads an error body here; an unclosed HTTPError is a ResourceWarning on 3.14
            except Exception:
                pass
            if e.code not in (301, 302, 303, 307, 308):
                raise
            if not location:
                raise ValueError(f"a {e.code} with no Location from "
                                 f"{urllib.parse.urlparse(hop).hostname}") from None
            hop = civitai_safe_url(urllib.parse.urljoin(hop, location), hosts=redirect_hosts)
            # Every header is dropped on a hop, because a Bearer given for the first host must not
            # reach one the allowlist did not name. The User-Agent goes back on: it is not a
            # credential, and a storage CDN refuses urllib's default exactly as the API does.
            hdrs = {"User-Agent": FETCH_USER_AGENT}
    raise ValueError(f"more than {max_hops} redirects from {urllib.parse.urlparse(url).hostname}")


def civitai_token():
    """The token, from the environment or the base's own store.

    MEASURED on the pod 2026-09-11: CIVITAI_TOKEN is NOT in ComfyUI's process environment: the
    base keeps it in state/tokens.env, so reading only the environment would look like "no token"
    on a pod that has one.
    """
    tok = os.environ.get("CIVITAI_TOKEN") or os.environ.get("CIVITAI_API_KEY")
    if tok:
        return tok.strip()
    for path in (os.environ.get("BASE_STATE", "") and
                 os.path.join(os.environ["BASE_STATE"], "tokens.env"),
                 "/workspace/comfy-base/state/tokens.env"):
        try:
            if path and os.path.isfile(path):
                for line in open(path, encoding="utf-8"):
                    if line.startswith("CIVITAI_TOKEN="):
                        return line.split("=", 1)[1].strip().strip('"').strip("'")
        except Exception:
            pass
    return ""


def civitai_refusal(version):
    """Why this version may not be fetched, or None. Checked HERE as well as in the page, because
    a client can be made to say anything and these are the flags that matter: a real person's
    likeness, a minor, or a resource its author marked as not for NSFW use."""
    model = version.get("model") or {}
    for flag in REFUSED_FLAGS:
        if version.get(flag) or model.get(flag):
            return {"poi": "it depicts a real person",
                    "minor": "it depicts a minor",
                    "sfwOnly": "its author marked it SFW-only"}[flag]
    base = version.get("baseModel")
    if base == QWEN21_BASE:
        return None
    if base == QWEN2_BASE and is_qwen21_upload(version):
        return None
    return f"it is for {base or 'an unknown model'}, not Qwen Image 2.1"


def civitai_filename(version_id, name):
    """A name safe_lora_name will accept. Civitai filenames carry brackets, CJK and spaces."""
    stem = re.sub(r"[^A-Za-z0-9]+", "-", (name or "lora")).strip("-").lower()[:60] or "lora"
    return f"civitai_{int(version_id)}_{stem}.safetensors"
